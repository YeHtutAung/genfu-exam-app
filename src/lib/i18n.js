function getNestedValue(source, path) {
  return path.split('.').reduce((value, key) => value?.[key], source)
}

export function translate(language, key, params = {}) {
  const value =
    getNestedValue(translations[language], key) ??
    getNestedValue(translations[FALLBACK_LANGUAGE], key) ??
    key

  if (typeof value !== 'string') return key

  return value.replace(/\{(\w+)\}/g, (_, name) => params[name] ?? `{${name}}`)
}

export function localizedField(item, baseName, language, fallback = '') {
  if (!item) return fallback
  const suffix = language === 'ja' ? 'jp' : language
  return item[`${baseName}_${suffix}`] ?? item[`${baseName}_jp`] ?? item[baseName] ?? fallback
}

export const useLanguageStore = create(
  persist(
    (set) => ({
      language: FALLBACK_LANGUAGE,
      setLanguage: (language) => set({ language }),
    }),
    { name: 'genfu-language' }
  )
)

export function useI18n() {
  const language = useLanguageStore(s => s.language)
  const setLanguage = useLanguageStore(s => s.setLanguage)
  const t = useCallback((key, params) => translate(language, key, params), [language])
  const field = useCallback(
    (item, baseName, fallback) => localizedField(item, baseName, language, fallback),
    [language]
  )

  return {
    language,
    setLanguage,
    languages: LANGUAGES,
    t,
    field,
  }
}
